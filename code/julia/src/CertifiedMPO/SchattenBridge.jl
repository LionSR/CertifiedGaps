"""
    CertifiedGaps.CertifiedMPO.SchattenBridge

Conditional Schatten-norm bounds: the backward Gram-chain bound (`gram_chain_upper`) and the
operator-error to trace-moment bridge (`trace_upper`, `normalized_upper`). Moved verbatim
from spin2 `Spin2SchattenBridge`.
"""
module SchattenBridge

using ..CertifiedMPO: F

"An outward-rounded square root, checked by an exact rational inequality."
function rational_sqrt_upper(value::F; precision = 256)
    @assert value >= 0 && precision >= 32
    result = setprecision(BigFloat, precision) do
        setrounding(BigFloat, RoundUp) do
            F(sqrt(BigFloat(value, RoundUp)))
        end
    end
    @assert result >= 0 && result^2 >= value
    return result
end

"""
Conditional backward Schatten-norm bound for a compressed Gram chain.

Let B_j be C_j/kappa_j up to unitary changes of basis, with
||B_(j-1)' B_(j-1)-C_j||_HS <= hs_errors[j], and optional operator
error bounds. If terminal_hs >= ||B_k||_HS, the returned initial_norm
bounds ||A_0||_(2^(k+1)), given the supplied error bounds for A_0-B_0.

At p_j=2^(k+1-j), Schatten monotonicity and the triangle inequality give
||B_(j-1)||_(2p_j)^2 <= kappa_j ||B_j||_p_j
    + min(hs_errors[j], dimension^(1/p_j) operator_errors[j]).
Every dimension root and norm root is rounded upward and checked exactly.
This routine does not verify any matrix/MPO input certificate.
"""
function gram_chain_upper(
    terminal_hs::F,
    normalizations,
    hs_errors;
    dimension::Integer,
    operator_errors = fill(nothing, length(hs_errors)),
    initial_hs_error = F(0),
    initial_operator_error = nothing,
    root_upper = rational_sqrt_upper,
)
    k = length(normalizations)
    @assert length(hs_errors) == length(operator_errors) == k
    @assert dimension >= 1 && terminal_hs >= 0
    @assert all(>(0), normalizations) && all(>=(0), hs_errors)
    @assert all(e -> isnothing(e) || e >= 0, operator_errors)
    @assert !isnothing(initial_hs_error) || !isnothing(initial_operator_error)
    @assert isnothing(initial_hs_error) || initial_hs_error >= 0
    @assert isnothing(initial_operator_error) || initial_operator_error >= 0
    function root(value)
        upper = F(root_upper(F(value)))
        @assert upper >= 0 && upper^2 >= value
        return upper
    end
    norms, dimension_roots = fill(F(0), k+1), fill(F(0), k+1)
    local_errors = fill(F(0), k)
    norms[end], dimension_roots[end] = terminal_hs, root(F(dimension))
    for j in k:-1:1
        op = operator_errors[j]
        local_errors[j] =
            isnothing(op) ? F(hs_errors[j]) : min(F(hs_errors[j]), dimension_roots[j+1]*op)
        norms[j] = root(normalizations[j]*norms[j+1]+local_errors[j])
        dimension_roots[j] = root(dimension_roots[j+1])
    end
    initial_error = if isnothing(initial_hs_error)
        dimension_roots[1]*initial_operator_error
    elseif isnothing(initial_operator_error)
        F(initial_hs_error)
    else
        min(F(initial_hs_error), dimension_roots[1]*initial_operator_error)
    end
    return (;
        initial_norm = norms[1]+initial_error,
        candidate_norms = norms,
        dimension_roots,
        local_errors,
        initial_error,
        power = big(2)^(k+1),
    )
end

"""
Conditional operator-error to trace-moment bridge.

If A>=0, ||A-B||_op<=eta, and Tr[(B'*B)^(p/2)]<=moment,
then Tr(A^p) is at most the returned rational expression.
Here p is an even positive integer and dimension is the full Hilbert dimension.
Singular-value perturbation gives s_i(A)<=s_i(B)+eta; weighted convexity
bounds (x+y)^p by (1+t)^(p-1)x^p+(1+1/t)^(p-1)y^p.
No operator-error or moment input is generated by this scalar function.
"""
function trace_upper(moment::F, eta::F, dimension::Integer, p::Integer, t::F)
    @assert moment >= 0 && eta >= 0 && dimension >= 1 && p >= 2 && iseven(p) && t > 0
    first = (1+t)^(p-1)*moment
    floor = dimension*(1+inv(t))^(p-1)*eta^p
    return (; upper = first+floor, moment_contribution = first, floor_contribution = floor)
end

"Normalized planning bound when Tr|B|^p<=1 and dim^(1/p) is the given exact integer."
function normalized_upper(dimension_root::Integer, p::Integer, relative_error::F)
    @assert dimension_root >= 1 && iseven(p) && p >= 2 && relative_error >= 0
    iszero(relative_error) && return F(1)
    t = dimension_root*relative_error
    certificate = trace_upper(F(1), relative_error, big(dimension_root)^p, p, t)
    @assert certificate.upper == (1+t)^p
    return certificate.upper
end

end
