# Generate `lean/SeedKernel/Heisenberg/OpenTrialData.lean`, the data behind the kernel-checked
# open-chain trial bound (`lean/SeedKernel/Heisenberg/OpenTrial.lean`).
#
#   julia --project=models/lean_seeds models/lean_seeds/scripts/open_trial/generate.jl
#   julia --project=models/lean_seeds models/lean_seeds/scripts/open_trial/generate.jl --check
#
# The first form writes the file, the second compares it with a fresh generation.
#
# The data are untrusted: Lean recomputes every output. This script runs the same iteration in
# exact integer arithmetic, checks the block totals against a direct contraction on the doubled
# space and against the paper's `trial-exact-results.json`, so that a regenerated file is known to
# pass before Lean is run. It needs the upstream evidence of both papers
# (`julia tools/fetch_upstream.jl` and `julia tools/fetch_upstream.jl --boundary`).
include(joinpath(@__DIR__, "..", "..", "src", "open_trial.jl"))
using .OpenTrialSeed

const LEAN_FILE = joinpath(OpenTrialSeed.REPO, "lean", "SeedKernel", "Heisenberg",
    "OpenTrialData.lean")

"Sparse `(index, value)` list (0-based) of the nonzero entries of a vector, as Lean source."
sparse_list(v) = "[" * join(["($(i - 1), $(v[i]))" for i in eachindex(v) if !iszero(v[i])],
    ", ") * "]"

function generate()
    r = OpenTrialSeed.reduce_blocks()
    labels = OpenTrialSeed.TrialSeed.operators().labels
    b, c = OpenTrialSeed.endpoints(labels)
    io = IOBuffer()
    p(xs...) = println(io, xs...)
    p("""/-
Copyright (c) 2026 thermal-mpo-gap contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: thermal-mpo-gap contributors
-/
import SeedKernel.Heisenberg.TrialLinear

/-!
# Data of the open-chain trial bound (generated)

GENERATED by `models/lean_seeds/scripts/open_trial/generate.jl`; do not edit. Every number here
is untrusted input: `OpenTrialBlocks` recomputes the outputs in the kernel.

* `openLeftSparse`, `openRightSparse`: the endpoint columns `b` and `c` of the opposite-field
  trial vectors (`b = βᵢ`, `c = κᵢ βᵢ` on the label `d = -1` of multiplet `i`), as
  `(label, value)` lists.
* `openWidths`: per block `b = 0, …, 10`, the lane widths of the packed products by `tᵦ` and by
  `oᵦ`.
* `openOutputs`: per block, for `m = 34, 78, 142, 240`, the triple
  `(ℓ tᵐ ν, zₘ ν, ℓ tᵐ⁻¹ ν′)` of the block iteration (`OpenTrialCompute.blockOut`).
-/

namespace SeedKernel.OpenTrial

-- The integer literals cannot be wrapped.
set_option linter.style.longLine false
""")
    p("/-- The left endpoint `b` as `(label, value)` pairs. -/")
    p("def openLeftSparse : List (ℕ × ℤ) := ", sparse_list(b))
    p()
    p("/-- The right endpoint `c` as `(label, value)` pairs. -/")
    p("def openRightSparse : List (ℕ × ℤ) := ", sparse_list(c))
    p()
    p("/-- Lane widths `(w_t, w_o)` of the packed products of each block. -/")
    p("def openWidths : List (ℕ × ℕ) := [", join(["($(x.Wt), $(x.Wo))" for x in r.blocks], ", "),
        "]")
    p()
    p("/-- The outputs `(ℓ tᵐ ν, zₘ ν, ℓ tᵐ⁻¹ ν′)` of each block for `m = 34, 78, 142, 240`. -/")
    p("def openOutputs : List (List (ℤ × ℤ × ℤ)) := [")
    blocks = String[]
    for x in r.blocks
        rows = ["    ($(o[1]),\n     $(o[2]),\n     $(o[3]))" for o in x.outs]
        push!(blocks, "  [\n" * join(rows, ",\n") * "]")
    end
    p(join(blocks, ",\n"), "]")
    p()
    p("end SeedKernel.OpenTrial")
    return String(take!(io))
end

function main()
    text = generate()
    if "--check" in ARGS
        @assert isfile(LEAN_FILE) && read(LEAN_FILE, String) == text "OpenTrialData.lean is stale"
        println("PASS OpenTrialData.lean regenerates identically")
    else
        write(LEAN_FILE, text)
        println("wrote ", LEAN_FILE, " (", sizeof(text), " bytes)")
    end
end

main()
