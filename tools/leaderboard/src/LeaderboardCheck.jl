"""
    LeaderboardCheck

Validator for the leaderboard data `home_page/_data/records.yml`: the schema and tier enum,
the referenced paths, the rounded-down decimals of every exact bound (logarithms enclosed by the
outward-rounded rational `log_enclosure` of `CertifiedGaps`), agreement with the Lean records
generated by `lake exe leaderboard_audit`, and a scan of the Lean sources under `leaderboard/`
for escape hatches. The schema is documented at the top of `records.yml`.
"""
module LeaderboardCheck

using Dates
using JSON3
using YAML
using CertifiedGaps.ExactArithmetic: log_enclosure

export Report, check_records, scan_lean_sources, strip_lean_comments, parse_exact,
    parse_decimal, bound_enclosure, main

const TIERS = ("lean-unconditional", "lean-conditional", "certified", "unreviewed", "assumed",
    "target")
const LEAN_TIERS = Dict("lean-unconditional" => "unconditional",
    "lean-conditional" => "conditional")
# Tiers whose claim rests on a computer certificate in this repository.
const NEEDS_CERTIFICATE = ("lean-conditional", "certified", "unreviewed")
const STANDARD_AXIOMS = Set(["propext", "Classical.choice", "Quot.sound"])
const PARITIES = ("even", "odd", "all")
const BOUNDARIES = ("periodic", "open")
# Exact values longer than this are replaced on the page by `bound.precise`.
const MAX_SHOWN_VALUE = 24
const ID_PATTERN = r"^[a-z0-9]+(-[a-zA-Z0-9]+)*$"
const LEAN_NAME_PATTERN = r"^Leaderboard\.Records(\.[A-Za-z_][A-Za-z0-9_']*)+$"

"Errors (which fail the check) and warnings collected while validating."
struct Report
    errors::Vector{String}
    warnings::Vector{String}
    notes::Vector{String}
end
Report() = Report(String[], String[], String[])
err!(r::Report, msg) = (push!(r.errors, msg); r)
warn!(r::Report, msg) = (push!(r.warnings, msg); r)
note!(r::Report, msg) = (push!(r.notes, msg); r)
passed(r::Report) = isempty(r.errors)

"""
    parse_exact(x) -> Rational{BigInt}

Exact rational from an integer or a string: `"13480"`, `"-3/4"`, `"97//4"`, a decimal
`"413.4"`, or scientific notation `"4134e-1"` (the form Lean prints for `ℚ` literals).
Floating-point input is refused, since it would hide rounding.
"""
parse_exact(x::Integer) = BigInt(x) // big(1)
parse_exact(x::AbstractFloat) = throw(ArgumentError("floating-point value $x; write it as a string"))
function parse_exact(x::AbstractString)
    s = replace(strip(x), " " => "", "(" => "", ")" => "")
    m = match(r"^([+-]?\d+)//?(\d+)$", s)
    if m !== nothing
        den = parse(BigInt, m[2])
        den == 0 && throw(ArgumentError("zero denominator in \"$x\""))
        return parse(BigInt, m[1]) // den
    end
    m = match(r"^([+-]?)(\d+)(?:\.(\d+))?(?:[eE]([+-]?\d+))?$", s)
    m === nothing && throw(ArgumentError("not an exact number: \"$x\""))
    frac = something(m[3], "")
    q = parse(BigInt, m[2] * frac) // big(10)^length(frac)
    e = m[4] === nothing ? 0 : parse(Int, m[4])
    q = e >= 0 ? q * big(10)^e : q / big(10)^(-e)
    return m[1] == "-" ? -q : q
end
parse_exact(x) = throw(ArgumentError("not an exact number: $(repr(x))"))

"""
    parse_decimal(s) -> (q, k)

A displayed decimal `"0.3922"` as the exact rational `q` and its number of decimals `k`. The
value must be a string, so that YAML does not turn it into a float and drop trailing zeros.
"""
function parse_decimal(s)
    s isa AbstractString || throw(ArgumentError("decimal $(repr(s)) must be a quoted string"))
    m = match(r"^(\d+)\.(\d+)$", s)
    m === nothing && throw(ArgumentError("decimal \"$s\" must look like 0.1234"))
    return parse(BigInt, m[1] * m[2]) // big(10)^length(m[2]), length(m[2])
end

"""
    bound_enclosure(bound) -> (lo, hi)

Rational enclosure of the exact claim of a bound: log(r)/β for `{r, beta}` (outward-rounded),
or the point `value`.
"""
function bound_enclosure(b::AbstractDict)
    hasr, hasv = haskey(b, "r") || haskey(b, "beta"), haskey(b, "value")
    hasr && hasv && throw(ArgumentError("give either {r, beta} or {value}, not both"))
    if hasv
        v = parse_exact(b["value"])
        v > 0 || throw(ArgumentError("value must be positive"))
        return v, v
    end
    hasr || throw(ArgumentError("missing {r, beta} or {value}"))
    (haskey(b, "r") && haskey(b, "beta")) || throw(ArgumentError("need both r and beta"))
    r, β = parse_exact(b["r"]), parse_exact(b["beta"])
    r > 1 || throw(ArgumentError("r = $r must exceed 1"))
    β > 0 || throw(ArgumentError("beta = $β must be positive"))
    lo, hi = log_enclosure(r)
    return lo / β, hi / β
end

"""
    check_decimal!(report, where, decimal, lo, hi)

The decimal must be rounded down from the exact value in [lo, hi] (decimal ≤ lo) and be its
floor at the displayed precision (decimal + 10⁻ᵏ > hi).
"""
function check_decimal!(report, where, decimal, lo, hi)
    q, k = try
        parse_decimal(decimal)
    catch e
        return err!(report, "$where: $(sprint(showerror, e))")
    end
    q <= lo || err!(report, "$where: decimal $decimal exceeds the exact bound ≈ $(Float64(lo))")
    q + big(1) // big(10)^k > hi ||
        err!(report, "$where: decimal $decimal is not rounded at its precision (exact ≈ $(Float64(hi)))")
    return report
end

getk(d, k) = d isa AbstractDict ? get(d, k, nothing) : nothing

function check_path!(report, where, root, path; dir = false)
    path isa AbstractString || return err!(report, "$where: path must be a string")
    (isabspath(path) || occursin("..", path)) &&
        return err!(report, "$where: path \"$path\" must be relative to the repository root")
    full = joinpath(root, path)
    ok = dir ? isdir(full) : isfile(full)
    ok || err!(report, "$where: $(dir ? "directory" : "file") \"$path\" does not exist")
    return report
end

function check_date!(report, where, d)
    d isa Date && return report
    if d isa AbstractString
        try
            Date(d, dateformat"yyyy-mm-dd")
            return report
        catch
        end
    end
    return err!(report, "$where: date $(repr(d)) is not yyyy-mm-dd")
end

function check_exact_field!(report, where, x; positive = true)
    try
        q = parse_exact(x)
        positive && q <= 0 && err!(report, "$where: must be positive")
    catch e
        err!(report, "$where: $(sprint(showerror, e))")
    end
    return report
end

"""
    lean_covers(lean, leanbound, bound, headline, lengths) -> Bool

Whether the Lean theorem `Δ_L > log(r)/β` for every even `L ≥ lean.L0` implies the headline
claim: the Lean value is at least the headline value (exactly: identical `{r, beta}`, or
disjoint outward enclosures) and the Lean lengths include the headline lengths (even periodic
rings with `lean.L0 ≤ lengths.L0`). Throws when the enclosures overlap and cannot decide.
"""
function lean_covers(lean, leanbound, bound, headline, lengths)
    longer = getk(lengths, "parity") == "even" &&
        something(getk(lengths, "boundary"), "periodic") == "periodic" &&
        getk(lean, "L0") isa Integer && getk(lengths, "L0") isa Integer &&
        getk(lean, "L0") <= getk(lengths, "L0")
    same = haskey(bound, "r") && parse_exact(bound["r"]) == parse_exact(getk(lean, "r")) &&
        parse_exact(bound["beta"]) == parse_exact(getk(lean, "beta"))
    stronger = if same
        true
    elseif leanbound[1] >= headline[2]
        true
    elseif leanbound[2] < headline[1]
        false
    else
        throw(ArgumentError("cannot decide whether the Lean bound is at least the headline bound"))
    end
    return longer && stronger
end

"Lean records keyed by name, from the JSON array written by `lake exe leaderboard_audit`."
function load_lean_records(path)
    data = JSON3.read(read(path, String))
    data isa JSON3.Array || throw(ArgumentError("$path: expected a JSON array of records"))
    out = Dict{String,Any}()
    for rec in data
        name = String(rec[:name])
        haskey(out, name) && throw(ArgumentError("$path: duplicate Lean record $name"))
        out[name] = rec
    end
    return out
end

function check_lean_record!(report, where, lean, json)
    rec = get(json, lean["name"], nothing)
    rec === nothing && return err!(report, "$where: Lean record $(lean["name"]) is not in lean_records.json")
    jL0 = get(rec, :L0, nothing)
    jL0 == get(lean, "L0", missing) ||
        err!(report, "$where: L0 = $(get(lean, "L0", nothing)) in YAML but $jL0 in Lean")
    for key in ("r", "beta")
        try
            parse_exact(lean[key]) == parse_exact(string(rec[Symbol(key)])) ||
                err!(report, "$where: $key = $(lean[key]) in YAML but $(rec[Symbol(key)]) in Lean")
        catch e
            err!(report, "$where: cannot compare $key: $(sprint(showerror, e))")
        end
    end
    axioms = Set(String.(get(rec, :axioms, String[])))
    extra = setdiff(axioms, STANDARD_AXIOMS)
    isempty(extra) || err!(report, "$where: Lean record uses nonstandard axioms $(sort!(collect(extra)))")
    kind = get(rec, :kind, nothing)
    hyp = get(rec, :hypothesis, nothing)
    kind in ("unconditional", "conditional") || err!(report, "$where: unknown Lean kind $(repr(kind))")
    kind == "unconditional" && hyp !== nothing &&
        err!(report, "$where: unconditional Lean record carries a hypothesis")
    kind == "conditional" && hyp === nothing &&
        err!(report, "$where: conditional Lean record has no hypothesis")
    return kind
end

"""
    check_records(records_path; root, lean_records = nothing) -> (report, summary)

Validate `records.yml` against the schema in its header comment. `root` is the repository root
for the referenced paths; `lean_records` is the path of the generated `lean_records.json`
(skipped when `nothing`). `summary` maps each tier to its number of records.
"""
function check_records(records_path; root, lean_records = nothing)
    report = Report()
    summary = Dict(t => 0 for t in TIERS)
    data = try
        YAML.load_file(records_path)
    catch e
        err!(report, "$records_path: YAML parse error: $(sprint(showerror, e))")
        return report, summary
    end
    data isa AbstractDict || return err!(report, "$records_path: top level must be a mapping"), summary
    for key in keys(data)
        key in ("families", "records") || err!(report, "unknown top-level key \"$key\"")
    end
    families = Dict{String,Any}()
    for (i, fam) in enumerate(something(getk(data, "families"), Any[]))
        where = "families[$i]"
        key = getk(fam, "key")
        key isa AbstractString || (err!(report, "$where: missing key"); continue)
        haskey(families, key) && err!(report, "$where: duplicate family key $key")
        families[key] = fam
        for f in ("name", "hamiltonian")
            getk(fam, f) isa AbstractString || err!(report, "family $key: missing $f")
        end
        slug = getk(fam, "slug")
        slug === nothing || check_path!(report, "family $key", root, joinpath("models", slug); dir = true)
    end

    json = nothing
    if lean_records !== nothing
        json = try
            load_lean_records(lean_records)
        catch e
            err!(report, "lean records: $(sprint(showerror, e))")
            nothing
        end
    end
    used_lean = Set{String}()
    ids = Set{String}()
    records = getk(data, "records")
    records isa AbstractVector || return err!(report, "records must be a list"), summary
    for (i, rec) in enumerate(records)
        id = getk(rec, "id")
        where = id isa AbstractString ? "record $id" : "records[$i]"
        if !(id isa AbstractString) || match(ID_PATTERN, id) === nothing
            err!(report, "$where: id must be kebab-case")
        elseif id in ids
            err!(report, "$where: duplicate id")
        else
            push!(ids, id)
        end
        tier = getk(rec, "tier")
        if !(tier in TIERS)
            err!(report, "$where: tier $(repr(tier)) not one of $(join(TIERS, ", "))")
            continue
        end
        summary[tier] += 1
        fam = getk(rec, "family")
        haskey(families, fam) || err!(report, "$where: unknown family $(repr(fam))")
        getk(rec, "parameter") isa AbstractString || err!(report, "$where: missing parameter")
        slug = something(getk(rec, "slug"), getk(get(families, fam, nothing), "slug"), Some(nothing))
        slug === nothing || check_path!(report, where, root, joinpath("models", slug); dir = true)
        params = getk(rec, "params")
        if params !== nothing
            params isa AbstractDict || err!(report, "$where: params must be a mapping")
            params isa AbstractDict && for (k, v) in params
                check_exact_field!(report, "$where: params.$k", v; positive = false)
            end
        end
        gap = getk(rec, "numerical_gap")
        if gap !== nothing
            check_exact_field!(report, "$where: numerical_gap.value", getk(gap, "value"))
            getk(gap, "source") isa AbstractString || err!(report, "$where: numerical_gap needs a source")
        end

        if tier == "target"
            getk(rec, "bound") === nothing || err!(report, "$where: a target has no bound")
            getk(rec, "lean") === nothing || err!(report, "$where: a target has no Lean record")
            est = getk(rec, "estimate")
            est isa AbstractDict || err!(report, "$where: a target needs an estimate")
            if est isa AbstractDict
                for (k, v) in est
                    k in ("n0", "beta0", "float_bound") && check_exact_field!(report, "$where: estimate.$k", v)
                end
            end
            getk(rec, "source") isa AbstractDict || err!(report, "$where: a target needs a source")
            continue
        end

        lengths = getk(rec, "lengths")
        if lengths isa AbstractDict
            L0 = getk(lengths, "L0")
            (L0 isa Integer && L0 > 0) || err!(report, "$where: lengths.L0 must be a positive integer")
            getk(lengths, "parity") in PARITIES || err!(report, "$where: lengths.parity must be even, odd or all")
            getk(lengths, "unit") isa AbstractString || err!(report, "$where: lengths.unit missing")
            something(getk(lengths, "boundary"), "periodic") in BOUNDARIES ||
                err!(report, "$where: lengths.boundary must be periodic or open")
        else
            err!(report, "$where: missing lengths")
        end
        bound = getk(rec, "bound")
        headline = nothing
        if bound isa AbstractDict
            for k in keys(bound)
                k in ("r", "beta", "value", "strict", "decimal", "precise", "display") ||
                    err!(report, "$where: unknown bound field $k")
            end
            try
                headline = bound_enclosure(bound)
                check_decimal!(report, "$where: bound", getk(bound, "decimal"), headline...)
                precise = getk(bound, "precise")
                precise === nothing ||
                    check_decimal!(report, "$where: bound.precise", precise, headline...)
                # A long exact value (a dyadic rational from Float64 arithmetic) is not shown
                # on the page; its longer rounded-down decimal is.
                v = getk(bound, "value")
                v isa AbstractString && length(v) > MAX_SHOWN_VALUE && precise === nothing &&
                    err!(report, "$where: bound.value is longer than $MAX_SHOWN_VALUE characters; add bound.precise")
            catch e
                err!(report, "$where: bound: $(sprint(showerror, e))")
            end
        else
            err!(report, "$where: missing bound")
        end
        seed = getk(rec, "seed")
        if seed !== nothing
            n0 = getk(seed, "n0")
            (n0 isa Integer && n0 > 0) || err!(report, "$where: seed.n0 must be a positive integer")
            check_exact_field!(report, "$where: seed.beta0", getk(seed, "beta0"))
        elseif tier != "assumed"
            err!(report, "$where: missing seed")
        end
        check_date!(report, where, getk(rec, "date"))
        pr = getk(rec, "pr")
        (pr === nothing || (pr isa Integer && pr > 0)) || err!(report, "$where: pr must be a number or null")

        for (k, needed) in (("certificate", tier in NEEDS_CERTIFICATE), ("check", tier in NEEDS_CERTIFICATE))
            p = getk(rec, k)
            p === nothing ? (needed && err!(report, "$where: tier $tier needs $k")) :
                check_path!(report, "$where: $k", root, p)
        end
        if tier == "assumed" && getk(rec, "source") === nothing && getk(rec, "certificate") === nothing
            err!(report, "$where: an assumed result needs a source or a certificate")
        end

        lean = getk(rec, "lean")
        if haskey(LEAN_TIERS, tier) && !(lean isa AbstractDict)
            err!(report, "$where: tier $tier needs a lean record")
        elseif lean isa AbstractDict
            name = getk(lean, "name")
            if !(name isa AbstractString) || match(LEAN_NAME_PATTERN, name) === nothing
                err!(report, "$where: lean.name must be Leaderboard.Records.<Model>.<point>")
            else
                name in used_lean && err!(report, "$where: Lean record $name used twice")
                push!(used_lean, name)
            end
            L0 = getk(lean, "L0")
            (L0 isa Integer && L0 > 0) || err!(report, "$where: lean.L0 must be a positive integer")
            leanbound = nothing
            try
                leanbound = bound_enclosure(Dict("r" => getk(lean, "r"), "beta" => getk(lean, "beta")))
                dec = getk(lean, "decimal")
                dec === nothing || check_decimal!(report, "$where: lean", dec, leanbound...)
            catch e
                err!(report, "$where: lean: $(sprint(showerror, e))")
            end
            # The headline badge is the Lean tier exactly when the Lean theorem implies the
            # headline claim; otherwise it is the certificate's tier.
            if leanbound !== nothing && headline !== nothing && lengths isa AbstractDict
                covers = try
                    lean_covers(lean, leanbound, bound, headline, lengths)
                catch e
                    err!(report, "$where: $(sprint(showerror, e))")
                    nothing
                end
                if covers === true && !haskey(LEAN_TIERS, tier)
                    err!(report, "$where: the Lean bound covers the headline bound, so the tier must be lean-unconditional or lean-conditional, not $tier")
                elseif covers === false && haskey(LEAN_TIERS, tier)
                    err!(report, "$where: tier $tier but the Lean bound is weaker than the headline bound (or covers fewer lengths); use the certificate's tier")
                end
            end
            if json !== nothing && name isa AbstractString
                kind = check_lean_record!(report, where, lean, json)
                haskey(LEAN_TIERS, tier) && kind !== nothing && kind != LEAN_TIERS[tier] &&
                    err!(report, "$where: tier $tier but the Lean record is $kind")
            end
        end

        previous = nothing
        for (j, h) in enumerate(something(getk(rec, "history"), Any[]))
            hw = "$where: history[$j]"
            check_date!(report, hw, getk(h, "date"))
            key = try
                (string(getk(h, "date")), first(parse_decimal(getk(h, "decimal"))))
            catch e
                err!(report, "$hw: $(sprint(showerror, e))")
                nothing
            end
            # Rendered in file order: newest first, and the larger bound first on a shared date.
            if key !== nothing && previous !== nothing && (key[1] > previous[1] ||
                    (key[1] == previous[1] && key[2] > previous[2]))
                err!(report, "$hw: history must be newest first, larger bound first on the same date")
            end
            key === nothing || (previous = key)
            getk(h, "method") isa AbstractString || err!(report, "$hw: missing method")
            getk(h, "tier") in TIERS || err!(report, "$hw: tier must be one of $(join(TIERS, ", "))")
        end
    end
    if json !== nothing
        for name in sort!(collect(setdiff(keys(json), used_lean)))
            warn!(report, "Lean record $name has no entry in records.yml")
        end
        note!(report, "$(length(used_lean)) Lean records matched against $(length(json)) in lean_records.json")
    end
    return report, summary
end

"""
    strip_lean_comments(src) -> String

Lean source with line comments and (nested) block comments, including docstrings, replaced by
spaces, and the contents of string literals likewise, so that a word such as `sorry` in prose or
in a message does not trip the scan. Newlines are kept, so line numbers survive.
"""
function strip_lean_comments(src::AbstractString)
    out = IOBuffer()
    chars = collect(src)
    i, n, depth, instring = 1, length(chars), 0, false
    while i <= n
        c = chars[i]
        nxt = i < n ? chars[i+1] : '\0'
        if depth == 0 && instring
            if c == '\\' && i < n
                print(out, "  "); i += 2; continue
            end
            c == '"' ? (instring = false; print(out, c)) : print(out, c == '\n' ? c : ' ')
        elseif depth == 0 && c == '"'
            instring = true; print(out, c)
        elseif c == '/' && nxt == '-'
            depth += 1; print(out, "  "); i += 2; continue
        elseif depth > 0 && c == '-' && nxt == '/'
            depth -= 1; print(out, "  "); i += 2; continue
        elseif depth == 0 && c == '-' && nxt == '-'
            while i <= n && chars[i] != '\n'
                print(out, ' '); i += 1
            end
            continue
        else
            print(out, depth > 0 && c != '\n' ? ' ' : c)
        end
        i += 1
    end
    return String(take!(out))
end

const FORBIDDEN = [
    (r"\bsorry\b", "sorry"),
    (r"\bnative_decide\b", "native_decide"),
    (r"(^|\s)axiom\s", "axiom declaration"),
    (r"debug\.skipKernelTC", "set_option debug.skipKernelTC"),
    (r"@\[[^\]]*\b(implemented_by|extern)\b", "implemented_by/extern attribute"),
    (r"\bLean\.ofReduceBool\b|\bofReduceBool\b", "ofReduceBool"),
]

"""
    scan_lean_sources(dir) -> Vector{String}

Every forbidden construct (sorry, native_decide, axiom declarations, kernel type-check skipping,
implemented_by/extern) in the `.lean` files under `dir`, outside comments, as
`path:line: what`. Empty when `dir` does not exist.
"""
function scan_lean_sources(dir)
    hits = String[]
    isdir(dir) || return hits
    for (base, _, files) in walkdir(dir), f in sort(files)
        endswith(f, ".lean") || continue
        path = joinpath(base, f)
        for (ln, line) in enumerate(split(strip_lean_comments(read(path, String)), '\n'))
            for (re, what) in FORBIDDEN
                occursin(re, line) && push!(hits, "$(relpath(path, dirname(dir))):$ln: $what")
            end
        end
    end
    return hits
end

const USAGE = """
usage: julia --project=tools/leaderboard tools/leaderboard/check_records.jl [options]
  --records PATH       leaderboard data (default home_page/_data/records.yml)
  --lean-records PATH  lean_records.json from `lake exe leaderboard_audit` (optional)
  --lean-dir PATH      Lean sources to scan (default leaderboard/)
  --root PATH          repository root (default: two levels above this tool)
"""

"Command-line entry point; returns the process exit code."
function main(args; default_root = normpath(joinpath(@__DIR__, "..", "..", "..")))
    opts = Dict("--root" => default_root)
    i = 1
    while i <= length(args)
        a = args[i]
        if a in ("-h", "--help")
            print(USAGE); return 0
        elseif a in ("--records", "--lean-records", "--lean-dir", "--root") && i < length(args)
            opts[a] = args[i+1]; i += 2
        else
            print(stderr, "unknown argument $a\n", USAGE); return 2
        end
    end
    root = opts["--root"]
    records = get(opts, "--records", joinpath(root, "home_page", "_data", "records.yml"))
    lean_dir = get(opts, "--lean-dir", joinpath(root, "leaderboard"))
    report, summary = check_records(records; root, lean_records = get(opts, "--lean-records", nothing))
    haskey(opts, "--lean-records") || note!(report, "no --lean-records given: Lean records not compared")
    hits = scan_lean_sources(lean_dir)
    isdir(lean_dir) || note!(report, "no Lean directory $lean_dir: source scan skipped")
    for h in hits
        err!(report, "forbidden construct in Lean source: $h")
    end

    println("Leaderboard records: $(sum(values(summary))) in $records")
    for t in TIERS
        println("  ", rpad(t, 20), lpad(summary[t], 4))
    end
    foreach(m -> println("note: ", m), report.notes)
    foreach(m -> println("warning: ", m), report.warnings)
    foreach(m -> println(stderr, "error: ", m), report.errors)
    if passed(report)
        println("PASSED")
        return 0
    end
    println(stderr, "FAILED: $(length(report.errors)) error(s)")
    return 1
end

